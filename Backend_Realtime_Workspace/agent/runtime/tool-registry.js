// ============================================================================
// TeamSpot — Tool Registry
// Registers, filters, and manages agent tools with permission checks
// ============================================================================

import { DynamicStructuredTool } from "@langchain/core/tools";
import { z } from "zod";
import { createLogger } from "../../observability/logger.js";

const log = createLogger("ToolRegistry");

export class ToolRegistry {
  constructor() {
    /** @type {Map<string, Object>} */
    this.tools = new Map();
    this._registerBuiltinTools();
  }

  register(name, config) {
    this.tools.set(name, config);
    log.debug("Tool registered", { name });
  }

  /** Get tools filtered by user permissions */
  getTools({ userId, tenantId, workspaceId, permissions = {} } = {}) {
    const filtered = [];
    for (const [name, config] of this.tools) {
      if (config.requiredPermission && !permissions[config.requiredPermission]) continue;
      filtered.push(
        new DynamicStructuredTool({
          name,
          description: config.description,
          schema: config.schema,
          func: async (args) => config.handler({ ...args, _ctx: { userId, tenantId, workspaceId, permissions } }),
        })
      );
    }
    return filtered;
  }

  _registerBuiltinTools() {
    // ── Search workspace knowledge ─────────────────────────────────
    this.register("search_workspace", {
      description: "Search workspace documents, messages, and knowledge base using semantic search",
      schema: z.object({ query: z.string().describe("Search query"), limit: z.number().optional().default(5) }),
      handler: async ({ query, limit, _ctx }) => {
        // Delegate to RAG retriever (imported lazily to avoid circular deps)
        const { Retriever } = await import("../knowledge/retriever.js");
        return Retriever.search(query, { tenantId: _ctx.tenantId, workspaceId: _ctx.workspaceId, userId: _ctx.userId, limit });
      },
    });

    // ── Create task ────────────────────────────────────────────────
    this.register("create_task", {
      description: "Create a new task in a project",
      requiredPermission: "canCreateTasks",
      schema: z.object({
        title: z.string(), description: z.string().optional(),
        projectId: z.string(), priority: z.enum(["low", "medium", "high", "critical"]).optional(),
        assignedTo: z.string().optional(), dueDate: z.string().optional(),
      }),
      handler: async ({ title, description, projectId, priority, assignedTo, dueDate, _ctx }) => {
        const Task = (await import("../../modules/tasks/models/task.model.js")).default;
        const task = await Task.create({
          title, description, projectId, priority, assignedTo, dueDate: dueDate ? new Date(dueDate) : undefined,
          tenantId: _ctx.tenantId, workspaceId: _ctx.workspaceId, createdBy: _ctx.userId,
        });
        return { success: true, taskId: task._id, title: task.title };
      },
    });

    // ── List project tasks ────────────────────────────────────────
    this.register("list_tasks", {
      description: "List tasks in a project with optional status filter",
      schema: z.object({ projectId: z.string(), status: z.string().optional(), limit: z.number().optional().default(20) }),
      handler: async ({ projectId, status, limit, _ctx }) => {
        const Task = (await import("../../modules/tasks/models/task.model.js")).default;
        const query = { projectId, tenantId: _ctx.tenantId };
        if (status) query.status = status;
        const tasks = await Task.find(query).select("title status priority assignedTo dueDate").limit(limit).lean();
        return { tasks, count: tasks.length };
      },
    });

    // ── Get meeting schedule ──────────────────────────────────────
    this.register("get_meetings", {
      description: "Get upcoming meetings for the user",
      schema: z.object({ limit: z.number().optional().default(10) }),
      handler: async ({ limit, _ctx }) => {
        const Meeting = (await import("../../modules/meetings/models/meeting.model.js")).default;
        const meetings = await Meeting.findUserMeetings(_ctx.userId, { limit });
        return { meetings: meetings.map((m) => ({ title: m.meetingTitle, date: m.meetingDate, status: m.status })) };
      },
    });

    // ── Summarize document ────────────────────────────────────────
    this.register("summarize_document", {
      description: "Summarize a document from the workspace knowledge base",
      schema: z.object({ documentId: z.string() }),
      handler: async ({ documentId, _ctx }) => {
        return { summary: `Document ${documentId} summary would be generated by RAG pipeline`, documentId };
      },
    });

    log.info("Builtin tools registered", { count: this.tools.size });
  }
}

export default ToolRegistry;
