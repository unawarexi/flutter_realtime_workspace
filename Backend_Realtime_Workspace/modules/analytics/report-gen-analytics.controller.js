import PDFDocument from "pdfkit";
import * as XLSX from "xlsx";
import {
  Document,
  Packer,
  Paragraph,
  TextRun,
  Table,
  TableRow,
  TableCell,
  WidthType,
  AlignmentType,
  HeadingLevel,
  BorderStyle,
} from "docx";

// ====================================================================================
// BRANDING CONFIGURATION
// ====================================================================================

const DEFAULT_BRANDING = {
  institutionName: "UNIDEL University",
  tagline: "Excellence in Education",
  primaryColor: "#F97316", // Orange
  secondaryColor: "#1E293B", // Slate dark
  accentColor: "#10B981", // Emerald for pass
  dangerColor: "#EF4444", // Red for fail
  footerText: "Generated by UNIDEL CBT System",
};

// ====================================================================================
// CSV GENERATOR
// ====================================================================================

export const generateCSV = (data, columns) => {
  if (!data || data.length === 0) return Buffer.from("");

  const headers = columns.map((col) => col.header).join(",");
  const rows = data.map((item) =>
    columns
      .map((col) => {
        const val = item[col.key] ?? "";
        const escaped = String(val).replace(/"/g, '""');
        return `"${escaped}"`;
      })
      .join(","),
  );

  return Buffer.from([headers, ...rows].join("\n"), "utf-8");
};

// ====================================================================================
// XLSX GENERATOR
// ====================================================================================

export const generateXLSX = (data, columns, sheetName = "Report") => {
  const worksheetData = [
    columns.map((col) => col.header),
    ...data.map((item) => columns.map((col) => item[col.key] ?? "")),
  ];

  const workbook = XLSX.utils.book_new();
  const worksheet = XLSX.utils.aoa_to_sheet(worksheetData);

  // Set column widths
  worksheet["!cols"] = columns.map(() => ({ wch: 20 }));

  XLSX.utils.book_append_sheet(workbook, worksheet, sheetName);

  return XLSX.write(workbook, { type: "buffer", bookType: "xlsx" });
};

// ====================================================================================
// DOCX GENERATOR
// ====================================================================================

export const generateDOCX = async (
  data,
  columns,
  title,
  subtitle,
  options = {},
) => {
  const { branding = DEFAULT_BRANDING } = options;

  const tableRows = [
    new TableRow({
      children: columns.map(
        (col) =>
          new TableCell({
            children: [
              new Paragraph({
                children: [new TextRun({ text: col.header, bold: true })],
              }),
            ],
            shading: { fill: "f2f2f2" },
          }),
      ),
    }),
    ...data.map(
      (item) =>
        new TableRow({
          children: columns.map(
            (col) =>
              new TableCell({
                children: [
                  new Paragraph({ text: String(item[col.key] ?? "") }),
                ],
              }),
          ),
        }),
    ),
  ];

  const doc = new Document({
    sections: [
      {
        properties: {},
        children: [
          new Paragraph({
            text: branding.institutionName,
            heading: HeadingLevel.HEADING_1,
            alignment: AlignmentType.CENTER,
          }),
          new Paragraph({
            text: title,
            heading: HeadingLevel.HEADING_2,
            alignment: AlignmentType.CENTER,
          }),
          new Paragraph({
            text: subtitle,
            alignment: AlignmentType.CENTER,
            spacing: { after: 400 },
          }),
          new Table({
            width: { size: 100, type: WidthType.PERCENTAGE },
            rows: tableRows,
          }),
          new Paragraph({
            text: branding.footerText,
            alignment: AlignmentType.CENTER,
            spacing: { before: 400 },
          }),
        ],
      },
    ],
  });

  return await Packer.toBuffer(doc);
};

// ====================================================================================
// BRANDED PDF GENERATOR
// ====================================================================================

export const generateBrandedPDF = async (
  data,
  columns,
  title,
  subtitle,
  options = {},
) => {
  const {
    branding = DEFAULT_BRANDING,
    showQuestionAnalysis = false,
    questionData = [],
    summary = null,
  } = options;

  return new Promise((resolve, reject) => {
    const doc = new PDFDocument({ margin: 50, size: "A4" });
    const chunks = [];

    doc.on("data", (chunk) => chunks.push(chunk));
    doc.on("end", () => resolve(Buffer.concat(chunks)));
    doc.on("error", reject);

    // ========== HEADER ==========
    doc
      .fontSize(18)
      .fillColor(branding.secondaryColor)
      .text(branding.institutionName, { align: "center" });
    doc
      .fontSize(10)
      .fillColor("#64748b")
      .text(branding.tagline, { align: "center" });
    doc.moveDown(0.5);

    // Orange accent line
    doc
      .moveTo(50, doc.y)
      .lineTo(doc.page.width - 50, doc.y)
      .strokeColor(branding.primaryColor)
      .lineWidth(2)
      .stroke();
    doc.moveDown(0.5);

    // Title and Subtitle
    doc
      .fontSize(16)
      .fillColor(branding.secondaryColor)
      .text(title, { align: "center" });
    doc.fontSize(10).fillColor("#64748b").text(subtitle, { align: "center" });
    doc.moveDown(1.5);

    // ========== SUMMARY SECTION (if provided) ==========
    if (summary) {
      doc
        .fontSize(12)
        .fillColor(branding.secondaryColor)
        .text("Summary", { underline: true });
      doc.moveDown(0.5);
      doc.fontSize(10).fillColor("#334155");

      Object.entries(summary).forEach(([key, value]) => {
        const label = key
          .replace(/([A-Z])/g, " $1")
          .replace(/^./, (s) => s.toUpperCase());
        doc.text(`${label}: ${value}`);
      });
      doc.moveDown(1);
    }

    // ========== DATA TABLE ==========
    const tableTop = doc.y;
    const colWidth = (doc.page.width - 100) / columns.length;

    // Table Header
    doc.fontSize(9).font("Helvetica-Bold").fillColor("#1e293b");
    columns.forEach((col, i) => {
      doc.text(col.header, 50 + i * colWidth, tableTop, {
        width: colWidth,
        align: "left",
      });
    });

    // Header underline
    doc
      .moveTo(50, tableTop + 12)
      .lineTo(doc.page.width - 50, tableTop + 12)
      .strokeColor("#cbd5e1")
      .lineWidth(1)
      .stroke();

    // Table Rows
    doc.font("Helvetica").fontSize(8);
    let currentY = tableTop + 20;

    data.forEach((item, rowIndex) => {
      // Page break check
      if (currentY > doc.page.height - 80) {
        doc.addPage();
        currentY = 50;

        // Redraw header on new page
        doc.fontSize(9).font("Helvetica-Bold").fillColor("#1e293b");
        columns.forEach((col, i) => {
          doc.text(col.header, 50 + i * colWidth, currentY, {
            width: colWidth,
            align: "left",
          });
        });
        doc
          .moveTo(50, currentY + 12)
          .lineTo(doc.page.width - 50, currentY + 12)
          .strokeColor("#cbd5e1")
          .lineWidth(1)
          .stroke();
        doc.font("Helvetica").fontSize(8);
        currentY += 20;
      }

      // Alternate row background
      if (rowIndex % 2 === 0) {
        doc.rect(50, currentY - 2, doc.page.width - 100, 16).fill("#f8fafc");
      }

      columns.forEach((col, i) => {
        let val = String(item[col.key] ?? "");

        // Color code status fields
        if (
          col.key === "status" ||
          col.key === "passed" ||
          col.key === "result"
        ) {
          const isPass =
            val.toLowerCase().includes("pass") ||
            val === "true" ||
            val === "Correct";
          doc.fillColor(isPass ? branding.accentColor : branding.dangerColor);
        } else {
          doc.fillColor("#334155");
        }

        doc.text(val, 50 + i * colWidth, currentY, {
          width: colWidth - 5,
          align: "left",
        });
      });

      currentY += 18;
    });

    // ========== QUESTION-BY-QUESTION ANALYSIS (if enabled) ==========
    if (showQuestionAnalysis && questionData.length > 0) {
      doc.addPage();
      doc
        .fontSize(14)
        .fillColor(branding.secondaryColor)
        .text("Question-by-Question Analysis", { align: "center" });
      doc.moveDown(1);

      questionData.forEach((q, idx) => {
        // Page break check
        if (doc.y > doc.page.height - 150) {
          doc.addPage();
        }

        const isCorrect = q.isCorrect;
        const statusColor = isCorrect
          ? branding.accentColor
          : branding.dangerColor;

        doc
          .fontSize(10)
          .fillColor(branding.secondaryColor)
          .text(`Q${idx + 1}: ${q.question}`, { continued: false });
        doc
          .fontSize(9)
          .fillColor("#64748b")
          .text(`Your Answer: ${q.studentAnswer || "No Answer"}`);
        doc.fillColor(statusColor).text(`Correct Answer: ${q.correctAnswer}`);
        doc
          .fillColor(statusColor)
          .text(isCorrect ? "✓ Correct" : "✗ Incorrect");
        doc.moveDown(0.8);
      });
    }

    // ========== FOOTER ==========
    const pageCount = doc.bufferedPageRange().count;
    for (let i = 0; i < pageCount; i++) {
      doc.switchToPage(i);

      // Footer line
      doc
        .moveTo(50, doc.page.height - 50)
        .lineTo(doc.page.width - 50, doc.page.height - 50)
        .strokeColor("#e2e8f0")
        .lineWidth(0.5)
        .stroke();

      // Footer text
      doc
        .fontSize(8)
        .fillColor("#94a3b8")
        .text(
          `${branding.footerText} | Page ${i + 1} of ${pageCount}`,
          50,
          doc.page.height - 40,
          { align: "center", width: doc.page.width - 100 },
        );
    }

    doc.end();
  });
};

// ====================================================================================
// LEGACY PDF GENERATOR (for backward compatibility)
// ====================================================================================

export const generatePDF = async (data, columns, title, subtitle) => {
  return generateBrandedPDF(data, columns, title, subtitle);
};